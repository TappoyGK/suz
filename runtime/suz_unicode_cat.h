static inline bool suz_cat_contains(const uint32_t table[][2], size_t count, uint32_t cp) {
    size_t lo = 0, hi = count;
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2;
        if (cp < table[mid][0]) hi = mid;
        else if (cp > table[mid][1]) lo = mid + 1;
        else return true;
    }
    return false;
}

/* 一般カテゴリ Z (Zs/Zl/Zp)・Cc・Cf かを判定する。 */
static inline bool suz_unicode_is_disallowed_char_literal(uint32_t cp) {
    if (cp < 0x80) return cp <= 0x20 || cp == 0x7f;
    return suz_cat_contains(suz_cat_disallowed, sizeof(suz_cat_disallowed) / sizeof(suz_cat_disallowed[0]), cp);
}

/* 一般カテゴリ M (Mn/Mc/Me) かを判定する。 */
static inline bool suz_unicode_is_mark(uint32_t cp) {
    if (cp < 0x80) return false;
    return suz_cat_contains(suz_cat_marks, sizeof(suz_cat_marks) / sizeof(suz_cat_marks[0]), cp);
}

/* 文字リテラルの名前構成文字（一般カテゴリ L・M・Nd または _）かを判定する。 */
static inline bool suz_unicode_is_char_name_unit(uint32_t cp) {
    if (cp < 0x80) {
        return (cp >= 'a' && cp <= 'z') || (cp >= 'A' && cp <= 'Z') ||
               (cp >= '0' && cp <= '9') || cp == '_';
    }
    return suz_cat_contains(suz_cat_name_nonascii, sizeof(suz_cat_name_nonascii) / sizeof(suz_cat_name_nonascii[0]), cp);
}
